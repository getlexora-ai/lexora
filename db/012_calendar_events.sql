-- Migration: Calendar events — per-user deadlines, renewals and review dates,
-- optionally anchored to a contract (Kündigungsfrist / notice deadlines,
-- Vertragsende, annual review).
--
-- The DB is the source of truth. Users get the dates into their real calendar
-- through a per-user read-only iCalendar subscription feed
-- (GET /api/calendar/feed/<token>.ics) — no OAuth, no data leaving the EU to a
-- US calendar processor, no two-way sync to keep consistent.
--
-- Recurrence model: ONE row per series, holding an RFC 5545 RRULE string plus
-- an EXDATE array; occurrences are expanded at read time
-- (src/lib/calendar-rrule.ts). Single-occurrence edits are stored as override
-- child rows (recurrence_parent_id + recurrence_id), exactly as RFC 5545 models
-- them. See docs/calendar/design.md for the rationale.
--
-- REQUIRES the base schema (contracts, set_updated_at(), pgcrypto).
-- Run:  psql "$DATABASE_URL_UNPOOLED" -f db/012_calendar_events.sql

-- ── Enums ───────────────────────────────────────────────────────────────────

-- What the date MEANS. Drives the icon/colour in the UI and the wording of the
-- reminder email; 'notice' is the Kündigungsfrist deadline (the last day you can
-- still terminate), 'renewal' the automatic extension date.
do $$ begin
  create type calendar_event_kind as enum
    ('deadline', 'notice', 'renewal', 'review', 'payment', 'other');
exception when duplicate_object then null;
end $$;

-- 'manual'  => the user created it by hand.
-- 'derived' => generated by applying a calendar_event_templates row to a
--              contract's key dates; regenerated when those dates change.
do $$ begin
  create type calendar_event_origin as enum ('manual', 'derived');
exception when duplicate_object then null;
end $$;

-- 'email'     => Lexora sends the mail itself (worker, not built yet).
-- 'ics_alarm' => emitted as a VALARM in the feed; the user's calendar app fires
--                it. Costs us nothing and works offline.
do $$ begin
  create type calendar_reminder_channel as enum ('email', 'ics_alarm');
exception when duplicate_object then null;
end $$;

do $$ begin
  create type reminder_dispatch_status as enum
    ('pending', 'sent', 'failed', 'skipped');
exception when duplicate_object then null;
end $$;

do $$ begin
  create type calendar_template_source as enum ('curated', 'user');
exception when duplicate_object then null;
end $$;

-- The contract date a template offsets FROM.
do $$ begin
  create type calendar_template_anchor as enum
    ('contract_start', 'contract_end', 'notice_deadline', 'signature_date', 'custom');
exception when duplicate_object then null;
end $$;


-- ── calendar_event_templates ────────────────────────────────────────────────
-- A reusable event SKELETON: "notice deadline, three months before contract
-- end", "annual review". Applying one to a contract's key dates produces a
-- derived calendar_events row (src/lib/calendar.ts applyTemplate).
--
-- user_id NULL => system-curated, visible to every user, read-only via the API
-- (same convention as clause_library / contract_templates / playbooks).
create table if not exists calendar_event_templates (
  id                 uuid primary key default gen_random_uuid(),
  user_id            text,                                  -- NULL = system-curated
  org_id             uuid references organisations (id) on delete cascade,

  name               text not null,                         -- German label (authoritative)
  name_en            text,
  description        text,

  kind               calendar_event_kind not null default 'deadline',
  contract_type      text not null default '',              -- '' = applies to any type

  -- Title with {{placeholders}}, rendered against the contract
  -- ({{contract_name}}, {{contract_type}}, {{notice_period}}).
  title_template     text not null,
  title_template_en  text,

  -- Anchor + signed ISO-8601 duration. '-P3M' from 'contract_end' is the
  -- classic three-month Kündigungsfrist deadline. Months/years are calendar
  -- arithmetic, so this stays an ISO string — never seconds.
  anchor             calendar_template_anchor not null default 'contract_end',
  offset_iso         text not null default 'P0D',

  all_day            boolean not null default true,
  -- Local wall-clock start when all_day is false. Interpreted in `time_zone`.
  default_time       time,
  default_duration_minutes int not null default 0,          -- 0 => 1 day (all-day) / 30 min (timed)
  time_zone          text not null default 'Europe/Berlin',

  -- RFC 5545 RRULE body without the "RRULE:" prefix, e.g. 'FREQ=YEARLY'.
  -- NULL => a one-off event.
  rrule              text,

  -- Reminder lead times applied to every event derived from this template.
  -- Signed ISO-8601 durations, negative = before: {'-P7D','-P1D'}.
  default_reminders  text[] not null default '{}',
  reminder_channel   calendar_reminder_channel not null default 'ics_alarm',

  source             calendar_template_source not null default 'user',
  doc_ref            text,                                  -- provenance; unique for curated rows
  is_default         boolean not null default false,        -- auto-apply to matching contracts

  deleted_at         timestamptz,
  created_at         timestamptz not null default now(),
  updated_at         timestamptz not null default now()
);

-- A curated template has no owner; every other one must have one.
do $$ begin
  alter table calendar_event_templates
    add constraint calendar_event_templates_owner_ck
    check ((source = 'curated') = (user_id is null));
exception when duplicate_object then null;
end $$;

-- Re-running a seed updates rather than duplicates.
create unique index if not exists calendar_event_templates_curated_ref_idx
  on calendar_event_templates (doc_ref) where source = 'curated';

create index if not exists calendar_event_templates_user_idx
  on calendar_event_templates (user_id, created_at desc) where deleted_at is null;

-- "Which templates auto-apply to a Mietvertrag?" — the only hot read.
create index if not exists calendar_event_templates_apply_idx
  on calendar_event_templates (contract_type) where is_default and deleted_at is null;

drop trigger if exists calendar_event_templates_updated_at on calendar_event_templates;
create trigger calendar_event_templates_updated_at
  before update on calendar_event_templates
  for each row execute function set_updated_at();


-- ── calendar_events ─────────────────────────────────────────────────────────
-- One row per SERIES (not per occurrence), plus override rows for
-- single-occurrence edits.
--
-- starts_at / ends_at are absolute instants (the first occurrence). `time_zone`
-- is what the recurrence expands in and what the .ics feed declares: a "3rd of
-- the month" deadline must stay on the 3rd across the DST switch, which only
-- works if expansion happens in local wall-clock time.
--
-- ends_at is EXCLUSIVE, matching RFC 5545 DTEND. An all-day event on
-- 2026-03-31 is [2026-03-31T00:00+02, 2026-04-01T00:00+02).
create table if not exists calendar_events (
  id                   uuid primary key default gen_random_uuid(),
  user_id              text not null,                       -- Clerk id; no FK, no RLS
  contract_id          uuid references contracts (id) on delete cascade,
  template_id          uuid references calendar_event_templates (id) on delete set null,

  title                text not null,
  description          text,
  location             text,
  kind                 calendar_event_kind not null default 'deadline',

  all_day              boolean not null default true,
  starts_at            timestamptz not null,
  ends_at              timestamptz not null,
  time_zone            text not null default 'Europe/Berlin',

  -- RFC 5545 RRULE body without the "RRULE:" prefix. NULL => one-off.
  rrule                text,
  -- Cancelled occurrences, keyed by their ORIGINAL start instant (RFC 5545 EXDATE).
  exdates              timestamptz[] not null default '{}',
  -- End of the last possible occurrence, denormalised at write time so a range
  -- query never has to expand the rule. NULL => the series never ends.
  series_end_at        timestamptz,

  -- RFC 5545 override: this row replaces ONE occurrence of its parent series.
  recurrence_parent_id uuid references calendar_events (id) on delete cascade,
  recurrence_id        timestamptz,                         -- original start it replaces
  -- Provenance for a "this and future" split: the series this one was cut from.
  split_from_id        uuid references calendar_events (id) on delete set null,

  origin               calendar_event_origin not null default 'manual',
  -- Stable identity of a derivation, e.g. '<template_id>:contract_end'. Lets
  -- regeneration be an idempotent upsert instead of delete-and-recreate.
  source_key           text,
  -- Set the moment a user edits a derived event. Regeneration then leaves the
  -- row alone and flags it as possibly stale instead of overwriting the edit.
  user_modified        boolean not null default false,

  deleted_at           timestamptz,
  created_at           timestamptz not null default now(),
  updated_at           timestamptz not null default now()
);

-- An override row must name the occurrence it replaces, and vice versa.
do $$ begin
  alter table calendar_events
    add constraint calendar_events_override_ck
    check ((recurrence_parent_id is null) = (recurrence_id is null));
exception when duplicate_object then null;
end $$;

-- A derived event must point at the contract it was derived from.
do $$ begin
  alter table calendar_events
    add constraint calendar_events_derived_ck
    check (origin = 'manual' or contract_id is not null);
exception when duplicate_object then null;
end $$;

do $$ begin
  alter table calendar_events
    add constraint calendar_events_span_ck check (ends_at >= starts_at);
exception when duplicate_object then null;
end $$;

-- THE query: "the signed-in user's events overlapping [from, to)". Predicate is
--   user_id = $1 and starts_at < $to and (series_end_at is null or series_end_at > $from)
-- so the index leads on (user_id, starts_at) and the series_end_at test is a
-- cheap filter on the handful of rows that survive.
create index if not exists calendar_events_user_range_idx
  on calendar_events (user_id, starts_at) where deleted_at is null;

-- Back-reference: "show me this contract's dates", and cascade bookkeeping.
create index if not exists calendar_events_contract_idx
  on calendar_events (contract_id, starts_at)
  where contract_id is not null and deleted_at is null;

-- Fold override rows into their series, and make "two overrides for the same
-- occurrence" impossible — the PATCH ?scope=this upsert targets this index.
create unique index if not exists calendar_events_override_idx
  on calendar_events (recurrence_parent_id, recurrence_id)
  where recurrence_parent_id is not null;

-- Regeneration upsert target: one derived event per (contract, derivation).
create unique index if not exists calendar_events_source_key_idx
  on calendar_events (contract_id, source_key)
  where source_key is not null and deleted_at is null;

-- Reminder worker scan: cross-user, date-led, so it must NOT lead on user_id.
create index if not exists calendar_events_due_scan_idx
  on calendar_events (starts_at)
  where deleted_at is null and recurrence_parent_id is null;

drop trigger if exists calendar_events_updated_at on calendar_events;
create trigger calendar_events_updated_at
  before update on calendar_events
  for each row execute function set_updated_at();


-- ── calendar_event_reminders ────────────────────────────────────────────────
-- A lead-time offset relative to an occurrence's start. Applies to EVERY
-- occurrence of the series, which is why it stores an offset and not a date.
--
-- offset_iso is the RFC 5545 TRIGGER value ('-P7D', '-P1D', '-PT1H'); negative
-- means before. offset_seconds is the same value normalised for the due-scan —
-- which is only exact for week/day/hour/minute/second components, so months and
-- years are rejected in the app layer (a three-month lead time is a separate
-- derived EVENT, not a reminder).
create table if not exists calendar_event_reminders (
  id              uuid primary key default gen_random_uuid(),
  event_id        uuid not null references calendar_events (id) on delete cascade,

  offset_iso      text not null,
  offset_seconds  int  not null,                            -- signed; -604800 for '-P7D'
  channel         calendar_reminder_channel not null default 'ics_alarm',
  label           text,                                     -- overrides the default VALARM text

  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now()
);

-- The same lead time twice on one event is always a mistake.
create unique index if not exists calendar_event_reminders_uniq_idx
  on calendar_event_reminders (event_id, offset_iso, channel);

create index if not exists calendar_event_reminders_event_idx
  on calendar_event_reminders (event_id);

-- Only 'email' reminders need a worker; 'ics_alarm' ones are just serialised.
create index if not exists calendar_event_reminders_email_idx
  on calendar_event_reminders (event_id) where channel = 'email';

drop trigger if exists calendar_event_reminders_updated_at on calendar_event_reminders;
create trigger calendar_event_reminders_updated_at
  before update on calendar_event_reminders
  for each row execute function set_updated_at();


-- ── reminder_dispatches ─────────────────────────────────────────────────────
-- Exactly-once ledger for fired reminders. The worker does NOT pre-materialise
-- a queue; it computes due (reminder, occurrence) pairs from the events table
-- and then CLAIMS each one with
--   insert ... on conflict (reminder_id, occurrence_start) do nothing returning id
-- Winning the insert is the lock: two workers racing the same occurrence, or a
-- retry after a crash, can never send twice.
create table if not exists reminder_dispatches (
  id               bigint generated always as identity primary key,
  reminder_id      uuid not null references calendar_event_reminders (id) on delete cascade,
  -- Denormalised so the ledger stays readable after a reminder is deleted-and-
  -- recreated, and so "what did we send about this event?" needs no join.
  event_id         uuid not null references calendar_events (id) on delete cascade,

  occurrence_start timestamptz not null,                    -- WHICH occurrence
  fire_at          timestamptz not null,                    -- occurrence_start + offset
  status           reminder_dispatch_status not null default 'pending',
  attempts         int not null default 0,
  error            text,

  created_at       timestamptz not null default now(),
  sent_at          timestamptz
);

-- The claim. Also the "did this already fire?" lookup.
create unique index if not exists reminder_dispatches_once_idx
  on reminder_dispatches (reminder_id, occurrence_start);

-- Worker retry sweep: claimed but not yet delivered.
create index if not exists reminder_dispatches_pending_idx
  on reminder_dispatches (fire_at) where status in ('pending', 'failed');

create index if not exists reminder_dispatches_event_idx
  on reminder_dispatches (event_id, occurrence_start);


-- ── calendar_feed_tokens ────────────────────────────────────────────────────
-- Bearer credential for the read-only .ics subscription. A calendar app cannot
-- run a Clerk session, so the URL itself is the credential.
--
-- A dedicated table rather than a column on a per-user settings row: Lexora has
-- no settings table today, rotation wants more than one live token at a time
-- (grace period), revocation should be a DELETE and not a row rewrite, and this
-- is the hottest UNAUTHENTICATED lookup in the product — a narrow table with a
-- single unique index is the cheapest possible probe.
create table if not exists calendar_feed_tokens (
  id             uuid primary key default gen_random_uuid(),
  user_id        text not null,                             -- Clerk id
  -- 32 random bytes, base64url. High entropy because this is the whole auth.
  token          text not null,
  label          text,                                      -- "iPhone", "Outlook"

  -- Observability for a credential that lives in a URL: is anything actually
  -- subscribed, and when did it last poll?
  last_used_at   timestamptz,
  last_user_agent text,
  use_count      bigint not null default 0,

  revoked_at     timestamptz,
  created_at     timestamptz not null default now()
);

create unique index if not exists calendar_feed_tokens_token_idx
  on calendar_feed_tokens (token);

create index if not exists calendar_feed_tokens_user_idx
  on calendar_feed_tokens (user_id) where revoked_at is null;
